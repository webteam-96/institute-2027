"""Write src/data/committees.js from the committee workbook.

    python scripts/committees-from-xlsx.py "path/to/Goa Institute Commitee.xlsx"

Reads the 'Committee' sheet: column A is the designation, C the name, and a
peach-filled row in A starts a new committee. The first five sections (Core
team, Institute Chair, Secretary, Treasurer, Advisor) are one committee, the
Core Team; every other section is its own. A yellow "Lenny" in the name column
is a placeholder the committee has not filled and is left out.
"""
import re
import sys

import openpyxl

HEADING = {'FFFFC599', 'FFF9CB9C'}   # peach: a section, or a sub-section
PLACEHOLDER = 'FFFFFF00'             # yellow
CORE = ['Core team', 'Institute Chair', 'Secretary', 'Treasurer', 'Advisor']
# spellings the committee has corrected since the workbook was sent
SPELL = {'Mannjoo Phadke': 'Manjoo Phadke', 'R B S Mani': 'Subramani Ramanujam', 'Sandeep Chouhan': 'Sandeep Chauhan'}

def fill(cell):
    f = cell.fill
    return f.fgColor.rgb if f is not None and f.fill_type == 'solid' else None

def tidy(s):
    s = re.sub(r'\s+', ' ', str(s)).strip()
    s = re.sub(r'\s*-\s*', '-', s)                     # "Co - Chair" -> "Co-Chair"
    s = s.replace('Co Chair', 'Co-Chair')
    s = s.replace('Resourse', 'Resources').replace('F& B', 'F&B').replace('Facilitaor', 'Facilitator')
    s = s.replace('Social media', 'Social Media')
    # "Vice-Chair-Technology" / "Jt. Secretary-Finance": the second hyphen joins a
    # post to its remit, and reads as a dash
    s = re.sub(r'^(Vice-Chair|Jt\. Secretary)-', r'\1 – ', s)
    return s

def name(s):
    s = re.sub(r'\s+', ' ', str(s)).strip()
    s = re.sub(r'\s*\(.*?\)\s*$', '', s)              # "( current DG )" is a note, not a name
    if s.isupper():                                    # PRABIR CHATTERJEE
        s = ' '.join(w if len(w) <= 2 else w.capitalize() for w in s.split(' '))
    s = re.sub(r'\.(?=[A-Za-z])', '. ', s)             # "H.BORSADWALA", "J.karthik"
    s = ' '.join(w if w == 'de' else w[0].upper() + w[1:] for w in s.split(' '))
    if ',' in s:                                       # "Sivasundaram, P"
        last, first = [p.strip() for p in s.split(',', 1)]
        s = f'{first}. {last}' if len(first) == 1 else f'{first} {last}'
    return SPELL.get(s, s)

def main(path):
    ws = openpyxl.load_workbook(path)['Committee -  ']
    groups = []
    for r in range(2, ws.max_row + 1):
        a, b, c = (ws.cell(r, i) for i in (1, 2, 3))
        if a.value is not None and fill(a) in HEADING and c.value is None:
            title = tidy(a.value)
            if title in CORE:
                if not groups or groups[0]['title'] != 'Core Team':
                    groups.insert(0, {'title': 'Core Team', 'members': []})
                current = groups[0]
            else:
                current = {'title': title, 'members': []}
                groups.append(current)
            continue
        if c.value is None:
            if a.value is not None and b.value is None and groups:   # a note under the heading
                current['note'] = tidy(a.value)
            continue
        if fill(c) == PLACEHOLDER and str(c.value).strip() == 'Lenny':
            continue
        role = tidy(a.value) if a.value is not None else ''
        bval = tidy(b.value) if b.value is not None else ''
        if bval.startswith('Aide to'):
            role = f'Aide to {name(a.value)}'          # A has the full name, B a short form
        elif bval.startswith('Facilitator'):
            role = 'Facilitator'
        elif isinstance(a.value, (int, float)):
            role = f'District {int(a.value)}'
        current['members'].append({'role': role, 'name': name(c.value)})

    def js(s):
        return "'" + s.replace("\\", "\\\\").replace("'", "\'") + "'"
    out = ['/* GENERATED by scripts/committees-from-xlsx.py from the committee workbook.',
           ' * Re-run that script on a new sheet rather than editing this file by hand. */',
           '',
           '/** Every committee, in the order the workbook lists them: a title, an',
           ' *  optional note, and its members as designation and name. */',
           'export const committees = [']
    for g in groups:
        out.append('  {')
        out.append(f"    title: {js(g['title'])},")
        if g.get('note'):
            out.append(f"    note: {js(g['note'])},")
        out.append('    members: [')
        for m in g['members']:
            out.append(f"      {{ role: {js(m['role'])}, name: {js(m['name'])} }},")
        out.append('    ],')
        out.append('  },')
    out.append(']')
    out.append('')
    with open('src/data/committees.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f"{len(groups)} committees, {sum(len(g['members']) for g in groups)} members")

if __name__ == '__main__':
    main(sys.argv[1])
